export const offset = (
  c: [number, number],
  x: number,
  y: number,
): [number, number] => [
  c[0] + x / (111320 * Math.cos((c[1] * Math.PI) / 180)),
  c[1] + y / 110574,
];
export function polygonAt(
  c: [number, number],
  points: number[][],
): GeoJSON.Polygon {
  const ring = points.map(([x, y]) => offset(c, x!, y!));
  return { type: "Polygon", coordinates: [[...ring, ring[0]!]] };
}
const rectangle = (
  c: [number, number],
  x: number,
  y: number,
  w: number,
  h: number,
) =>
  polygonAt(c, [
    [x - w / 2, y - h / 2],
    [x + w / 2, y - h / 2],
    [x + w / 2, y + h / 2],
    [x - w / 2, y + h / 2],
  ]);
